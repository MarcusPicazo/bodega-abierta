using System.Text.Json;
using System.Text.Json.Serialization;
using BodegaAbierta.Application.Abstractions;
using BodegaAbierta.Domain.Auditing;
using BodegaAbierta.Domain.Common;
using BodegaAbierta.Domain.FoodBanks;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Diagnostics;

namespace BodegaAbierta.Infrastructure.Auditing;

/// <summary>
/// Writes one <see cref="AuditEntry"/> per created/updated/deleted entity. It runs inside
/// SaveChanges, before the SQL is sent, so the audit rows are inserted in the same transaction as the
/// change: there is never a change without its audit entry, nor an audit entry for a rolled-back change.
/// </summary>
public sealed class AuditSaveChangesInterceptor(ICurrentUser currentUser, TimeProvider timeProvider) : SaveChangesInterceptor
{
    public const string AnonymousActor = "anonymous";

    private static readonly JsonSerializerOptions SnapshotJson = new()
    {
        Converters = { new JsonStringEnumConverter() },
    };

    public override InterceptionResult<int> SavingChanges(DbContextEventData eventData, InterceptionResult<int> result)
    {
        ArgumentNullException.ThrowIfNull(eventData);
        AddAuditEntries(eventData.Context);
        return base.SavingChanges(eventData, result);
    }

    public override ValueTask<InterceptionResult<int>> SavingChangesAsync(
        DbContextEventData eventData, InterceptionResult<int> result, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(eventData);
        AddAuditEntries(eventData.Context);
        return base.SavingChangesAsync(eventData, result, cancellationToken);
    }

    private void AddAuditEntries(DbContext? context)
    {
        if (context is null)
        {
            return;
        }

        context.ChangeTracker.DetectChanges();
        var actor = currentUser.UserId ?? AnonymousActor;
        var now = timeProvider.GetUtcNow();

        // Materialize first: adding AuditEntry instances while enumerating the tracker would modify it.
        var audits = context.ChangeTracker.Entries()
            .Where(e => e.Entity is not AuditEntry)
            .Select(e => CreateAuditEntry(e, actor, now))
            .OfType<AuditEntry>()
            .ToList();

        context.Set<AuditEntry>().AddRange(audits);
    }

    private static AuditEntry? CreateAuditEntry(EntityEntry entry, string actor, DateTimeOffset now)
    {
        var foodBankId = entry.Entity switch
        {
            ITenantOwned owned => owned.FoodBankId,
            FoodBank foodBank => foodBank.Id,
            _ => (Guid?)null,
        };

        if (foodBankId is null)
        {
            return null;
        }

        // The rowversion is noise for humans and is generated by the database anyway.
        var properties = entry.Properties
            .Where(p => !p.Metadata.IsPrimaryKey() && !p.Metadata.IsConcurrencyToken)
            .ToList();

        // TODO(Marcus): personal data must not leak into the audit log (LFPDPPP). Create
        // `[AttributeUsage(AttributeTargets.Property)] public sealed class AuditMaskedAttribute : Attribute`
        // in BodegaAbierta.Domain/Common, put it on Donor.Email and Donor.Phone, and here write "***"
        // instead of the value when p.Metadata.PropertyInfo has that attribute (keep null as null so
        // "had a value / didn't" is still visible). Remove the Skip from
        // AuditTrailTests.Donor_contact_data_is_masked_in_the_audit_log.

        (AuditAction Action, string? Before, string? After)? change = entry.State switch
        {
            EntityState.Added => (AuditAction.Created, null, Snapshot(properties, p => p.CurrentValue)),
            EntityState.Deleted => (AuditAction.Deleted, Snapshot(properties, p => p.OriginalValue), null),
            EntityState.Modified => ModifiedChange(properties),
            _ => null,
        };

        if (change is not { } c)
        {
            return null;
        }

        var key = entry.Metadata.FindPrimaryKey()!.Properties.Select(p => entry.Property(p.Name).CurrentValue);
        return new AuditEntry(
            foodBankId.Value,
            entry.Metadata.ClrType.Name,
            string.Join(",", key),
            c.Action,
            c.Before,
            c.After,
            actor,
            now);
    }

    /// <summary>Only properties whose value really changed; null if nothing did (no audit row).</summary>
    private static (AuditAction, string?, string?)? ModifiedChange(List<PropertyEntry> properties)
    {
        var changed = properties.Where(p => p.IsModified && !Equals(p.OriginalValue, p.CurrentValue)).ToList();
        return changed.Count == 0
            ? null
            : (AuditAction.Updated, Snapshot(changed, p => p.OriginalValue), Snapshot(changed, p => p.CurrentValue));
    }

    private static string Snapshot(IEnumerable<PropertyEntry> properties, Func<PropertyEntry, object?> value)
        => JsonSerializer.Serialize(properties.ToDictionary(p => p.Metadata.Name, value), SnapshotJson);
}
